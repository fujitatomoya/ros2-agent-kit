def errors(report):
    return [f.message for f in report.findings if f.level == ERROR]


class Sections(unittest.TestCase):

    def test_split_and_comments(self):
        secs = body.split_sections(PR_TEMPLATE)
        headings = [s.heading for s in secs if s.heading]
        self.assertEqual(headings[0], 'Description')
        self.assertIn('Did you use Generative AI?', headings)
        genai = body.section_map(PR_TEMPLATE)['did you use generative ai?']
        self.assertTrue(genai.is_empty)  # only an HTML comment

    def test_headings_inside_code_fences_are_ignored(self):
        text = '## A\n\n```\n# not a heading\n```\n'
        self.assertEqual([s.heading for s in body.split_sections(text) if s.heading], ['A'])


class PrBody(unittest.TestCase):

    def test_good_body_passes(self):
        report = body.check_pr_body(GOOD_PR, PR_TEMPLATE, OSRA, issue=1234)
        self.assertTrue(report.ok, report.format_text())

    def test_template_left_untouched_fails(self):
        report = body.check_pr_body(PR_TEMPLATE, PR_TEMPLATE, OSRA)
        msgs = errors(report)
        self.assertTrue(any('"Description" is empty' in m for m in msgs))
        self.assertTrue(any('Generative AI' in m and 'empty' in m for m in msgs))
        self.assertTrue(any('placeholder' in m for m in msgs))

    def test_missing_heading(self):
        text = GOOD_PR.replace('### Additional Information\n', '')
        report = body.check_pr_body(text, PR_TEMPLATE, OSRA)
        self.assertTrue(any('"Additional Information" is missing' in m for m in errors(report)))

    def test_wrong_issue_number(self):
        report = body.check_pr_body(GOOD_PR, PR_TEMPLATE, OSRA, issue=99)
        self.assertTrue(any('Fixes #99' in m for m in errors(report)))

    def test_fixes_url_form_accepted(self):
        text = GOOD_PR.replace('Fixes #1234', 'Fixes https://github.com/ros2/rclcpp/issues/1234')
        self.assertTrue(body.check_pr_body(text, PR_TEMPLATE, OSRA, issue=1234).ok)

    def test_disclosure_optional_under_app_profile(self):
        text = GOOD_PR.replace('Yes, Claude Code with claude-fable-5-1 drafted the unit test; '
                               'the fix is hand-written.\n', '')
        self.assertFalse(body.check_pr_body(text, PR_TEMPLATE, OSRA).ok)
        self.assertTrue(body.check_pr_body(text, PR_TEMPLATE, APP).ok)

    def test_no_template_generic_rules(self):
        report = body.check_pr_body('Just a sentence.\n', None, OSRA)
        self.assertFalse(report.ok)
        self.assertTrue(any('no "Generative AI"' in m for m in errors(report)))
        self.assertTrue(body.check_pr_body(GOOD_PR, None, OSRA).ok)

    def test_empty_body(self):
        self.assertFalse(body.check_pr_body('', PR_TEMPLATE, OSRA).ok)


class IssueForm(unittest.TestCase):

    def test_parse_bug_report_form(self):
        fields = body.parse_issue_form(BUG_FORM)
        by_id = {f.id: f for f in fields}
        self.assertEqual(by_id['os'].label, 'Operating System:')
        self.assertTrue(by_id['os'].required)
        self.assertIn('<PUT OS INFO HERE>', by_id['os'].placeholders)
        self.assertIn('<COPY OUTPUT HERE>', by_id['doctor'].placeholders)
        self.assertFalse(by_id['doctor'].required)
        self.assertEqual(by_id['generative_ai'].label, 'Generated by Generative AI')
        self.assertTrue(by_id['repro'].required)
        self.assertTrue(by_id['expected'].required)
        self.assertEqual([f.id for f in fields][:3], ['generative_ai', 'os', 'version'])

    def test_parse_feature_request_form(self):
        fields = body.parse_issue_form(FEATURE_FORM)
        labels = [f.label for f in fields]
        self.assertEqual(labels, ['Description', 'Motivation',
                                  'Design / Implementation Considerations', 'Additional Information'])
        self.assertTrue(fields[0].required)
        self.assertFalse(fields[2].required)


class IssueBody(unittest.TestCase):

    def test_good_bug_report(self):
        report = body.check_issue_body(GOOD_BUG, body.parse_issue_form(BUG_FORM), OSRA)
        self.assertTrue(report.ok, report.format_text())

    def test_missing_required_field(self):
        text = GOOD_BUG.replace('### Expected behavior\n\nNo crash.\n', '')
        report = body.check_issue_body(text, body.parse_issue_form(BUG_FORM), OSRA)
        self.assertTrue(any('"Expected behavior" is missing' in m for m in errors(report)))

    def test_placeholder_left(self):
        text = GOOD_BUG.replace('Linux host 6.8.0 #1 SMP x86_64 GNU/Linux', '<PUT OS INFO HERE>')
        report = body.check_issue_body(text, body.parse_issue_form(BUG_FORM), OSRA)
        self.assertTrue(any('placeholder <PUT OS INFO HERE>' in m for m in errors(report)))

    def test_disclosure_required_by_profile_only(self):
        text = GOOD_BUG.replace('Claude Code, claude-fable-5-1 collected the environment fields.',
                                '_No response_')
        fields = body.parse_issue_form(BUG_FORM)
        self.assertFalse(body.check_issue_body(text, fields, OSRA).ok)
        self.assertTrue(body.check_issue_body(text, fields, APP).ok)

    def test_empty_required_field(self):
        text = GOOD_BUG.replace('Segmentation fault.', '')
        report = body.check_issue_body(text, body.parse_issue_form(BUG_FORM), OSRA)
        self.assertTrue(any('"Actual behavior" is empty' in m for m in errors(report)))


if __name__ == '__main__':
    unittest.main()
